#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════
#  Dhad (ضاد) v1.2.3 — سكريبت الاختبارات الميدانية الموحد
#  المحاور: FAPS | الهمزات | التشكيل الفاسد | الضجيج الخفي | NFC/NFD
#  الاستخدام: cd ~/projects/dhad/dhad && bash field_tests.sh
# ══════════════════════════════════════════════════════════════
set -u

DHAD="cargo run --release --bin dhad-cli --quiet"

run() { printf '%s' "$1" | $DHAD; }

hdr() {
  echo ""
  echo "══════════════════════════════════════════════════════════════"
  echo "  $1"
  echo "══════════════════════════════════════════════════════════════"
}

# ──────────────────────────────────────────────────────────────
# المحور 1: FAPS — Presentation Forms & Ligatures
# ──────────────────────────────────────────────────────────────

hdr "اختبار 1A: Presentation Forms مقابل الحروف الأصلية"

# ﻛﺘﺎﺏ = U+FEDA (KAF final) + U+FE98 (TEH medial) + U+FE8E (ALEF final) + U+FE90 (BEH initial)
pf_text=$'\xEF\xBB\x9B\xEF\xBA\x98\xEF\xBA\x8E\xEF\xBA\x90'
normal_text="كتاب"

echo "--- Presentation Forms ---"
run "$pf_text"
echo -e "\n--- Normal Arabic ---"
run "$normal_text"

hdr "اختبار 1B: لام-ألف Ligatures (أخطر FAPS)"

# ﻻ = Lam-Alef ligature U+FEFB
lamalef_lig=$'\xEF\xBB\xBB'
lamalef_normal="لا"

echo "--- Lam-Alef Ligature U+FEFB ---"
run "$lamalef_lig"
echo -e "\n--- Lam + Alef Normal ---"
run "$lamalef_normal"

hdr "اختبار 1C: لام-ألف مع مدّة وهمزة (Ligatures المركبة)"

# ﻵ = Lam-Alef with Madda U+FEF5
lam_madda_lig=$'\xEF\xBB\xB5'
lam_madda_normal="لآ"

echo "--- Lam-Alef-Madda Ligature U+FEF5 ---"
run "$lam_madda_lig"
echo -e "\n--- Lam + Alef-Madda Normal ---"
run "$lam_madda_normal"

# ──────────────────────────────────────────────────────────────
# المحور 2: مقاعد الهمزة
# ──────────────────────────────────────────────────────────────

hdr "اختبار 2A: مقاعد الهمزة المختلفة"

echo "--- همزة على ألف: أ (U+0623) ---"
run "أ"
echo -e "\n--- همزة تحت ألف: إ (U+0625) ---"
run "إ"
echo -e "\n--- همزة على واو: ؤ (U+0624) ---"
run "ؤ"
echo -e "\n--- همزة على ياء (نبرة): ئ (U+0626) ---"
run "ئ"
echo -e "\n--- همزة مفردة على السطر: ء (U+0621) ---"
run "ء"
echo -e "\n--- ألف مدّة: آ (U+0622) ---"
run "آ"

hdr "اختبار 2B: سياق الهمزات — نفس الكلمة بتمثيلات مختلفة"

echo '--- "مسؤول" بهمزة على واو ---'
run "مسؤول"
echo -e '\n--- "مسئول" بهمزة على نبرة ---'
run "مسئول"

# ──────────────────────────────────────────────────────────────
# المحور 3: رفض التشكيل الفاسد
# ──────────────────────────────────────────────────────────────

hdr "اختبار 3A: تشكيل مكرّر (فتحة مرتين على نفس الحرف)"

echo "--- باء + فتحة واحدة (عادي) ---"
run $'ب\xD9\x8E'
echo -e "\n--- باء + فتحتين متتاليتين (يجب أن يُرفض) ---"
run $'ب\xD9\x8E\xD9\x8E'

hdr "اختبار 3B: تشكيل متناقض (فتحة + كسرة على نفس الحرف)"

echo "--- باء + فتحة + كسرة (تناقض — يجب أن يُرفض) ---"
run $'ب\xD9\x8E\xD9\x90'

hdr "اختبار 3C: شدة + تنوين (صالحة) مقابل تنوينان (غير صالح)"

echo "--- باء + شدة + تنوين ضم (صالح) ---"
run $'ب\xD9\x91\xD9\x8C'
echo -e "\n--- باء + تنوين ضم + تنوين فتح (تناقض — يجب أن يُرفض) ---"
run $'ب\xD9\x8C\xD9\x8B'

# ──────────────────────────────────────────────────────────────
# المحور 4: الضجيج الخفي (Noise Stripping)
# ──────────────────────────────────────────────────────────────

hdr "اختبار 4A: ZWJ/ZWNJ + BiDi controls (ضجيج خفي)"

# "كتاب" مع RLM في البداية + ZWJ + ZWNJ بين الحروف
zwj_text=$'\xE2\x80\x8F\xD9\x83\xE2\x80\x8D\xD8\xAA\xE2\x80\x8C\xD8\xA7\xD8\xA8'

echo "--- كتاب مع ZWJ+ZWNJ+RLM مخبأة ---"
run "$zwj_text"
echo -e "\n--- كتاب نظيفة ---"
run "كتاب"

hdr "اختبار 4B: BOM في منتصف النص"

# "كتاب" مع BOM (U+FEFF) في المنتصف
bom_mid=$'\xD9\x83\xD8\xAA\xEF\xBB\xBF\xD8\xA7\xD8\xA8'

echo "--- كتاب مع BOM مخبأ في المنتصف ---"
run "$bom_mid"
echo -e "\n--- كتاب نظيفة ---"
run "كتاب"

hdr "اختبار 4C: Variation Selectors (VS1-VS16)"

# "باب" مع Variation Selector 1 (U+FE00) بعد الباء
vs_text=$'\xD8\xA8\xEF\xB8\x80\xD8\xA7\xD8\xA8'

echo "--- باب مع Variation Selector مخبأ ---"
run "$vs_text"
echo -e "\n--- باب نظيفة ---"
run "باب"

# ──────────────────────────────────────────────────────────────
# المحور 5: NFC مقابل NFD — أخطر اختبار سيادة
# ──────────────────────────────────────────────────────────────

hdr "اختبار 5: NFC مقابل NFD — أخطر اختبار سيادة"

echo "--- آ precomposed U+0622 (NFC — يجب أن يُقبل) ---"
run $'\xD8\xA2'
echo -e "\n--- ألف + مدة U+0627+U+0653 (NFD — يجب أن يُرفض) ---"
run $'\xD8\xA7\xD9\x93'
echo -e "\n--- أ precomposed U+0623 (NFC — يجب أن يُقبل) ---"
run $'\xD8\xA3'
echo -e "\n--- ألف + همزة فوق U+0627+U+0654 (NFD — يجب أن يُرفض) ---"
run $'\xD8\xA7\xD9\x94'

echo ""
echo "══════════════════════════════════════════════════════════════"
echo "  انتهت جميع الاختبارات الميدانية — Dhad v1.2.3"
echo "══════════════════════════════════════════════════════════════"
